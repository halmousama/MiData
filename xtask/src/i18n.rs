//! i18n coverage gate (REBUILD_PLAN.md §7.4, docs/i18n.md).
//!
//! Two catalogues are the contract: `en.tsv` is the source and `fr.tsv` is first-class. This module
//! reads and measures them; [`gate`] holds the rules (orphan FR keys are fatal, unused EN keys are
//! fatal, the EN total may not shrink, missing FR keys may not grow).
//!
//! **Not-born state.** P0-1 shipped no `midata-i18n` crate (born in P0-2, D24), so the gate could not
//! measure anything and said so loudly, exiting 0 **only** because `docs/i18n-coverage.baseline`
//! recorded that exact state. The skip stays in the code — it is the honest answer if the catalogues
//! ever disappear — but it cannot be mistaken for a pass: the baseline now records a real
//! measurement, and either direction of drift fails.

mod gate;

use anyhow::{anyhow, bail, Context, Result};
use std::collections::BTreeSet;
use std::path::Path;

pub const EN_CATALOGUE: &str = "crates/midata-i18n/catalogues/en.tsv";
pub const FR_CATALOGUE: &str = "crates/midata-i18n/catalogues/fr.tsv";
pub const BASELINE: &str = "docs/i18n-coverage.baseline";

const BASELINE_HEADER: &str =
    "# GENERATED by `cargo xtask i18n-coverage --write-baseline` — do not hand-edit.\n\
# Ratchet: fr_missing may not increase and en_total may not decrease. state is either\n\
# `no-catalogues` (before midata-i18n is born, P0-1) or `catalogues` (the measurement).\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Catalogue {
    pub keys: BTreeSet<String>,
    pub duplicates: Vec<String>,
    pub malformed: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Coverage {
    pub en_total: usize,
    pub fr_total: usize,
    pub missing_fr: Vec<String>,
    pub orphan_fr: Vec<String>,
    /// Every source key, kept so the gate can ask which of them nothing references.
    pub en_keys: BTreeSet<String>,
}

impl Coverage {
    /// EN keys that have a French row.
    pub fn translated_fr(&self) -> usize {
        self.en_total.saturating_sub(self.missing_fr.len())
    }

    /// French coverage in whole percent (`0..=100`).
    pub fn fr_percent(&self) -> usize {
        self.translated_fr()
            .saturating_mul(100)
            .checked_div(self.en_total)
            .unwrap_or(0)
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CatalogueState {
    /// Neither catalogue exists: `midata-i18n` is not born yet.
    NotBorn,
    /// Both catalogues exist and parsed; coverage is measured.
    Born(Coverage),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BaselineState {
    NoCatalogues,
    Catalogues,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Baseline {
    state: BaselineState,
    en_total: usize,
    fr_missing: usize,
}

pub fn parse_catalogue(content: &str) -> Catalogue {
    let content = content.strip_prefix('\u{feff}').unwrap_or(content);
    let mut keys = BTreeSet::new();
    let mut duplicates = Vec::new();
    let mut malformed = Vec::new();

    for (index, raw) in content.lines().enumerate() {
        let line = raw.trim_end_matches('\r');
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((key, _text)) = line.split_once('\t') else {
            malformed.push(format!(
                "line {}: expected `key<TAB>text`",
                index.saturating_add(1)
            ));
            continue;
        };
        let key = key.trim();
        if key.is_empty() {
            malformed.push(format!("line {}: empty key", index.saturating_add(1)));
            continue;
        }
        if !keys.insert(key.to_string()) {
            duplicates.push(key.to_string());
        }
    }

    Catalogue {
        keys,
        duplicates,
        malformed,
    }
}

/// Measure the current catalogue state, or fail loudly on a half-born / invalid catalogue.
pub fn measure(root: &Path) -> Result<CatalogueState> {
    let en_path = root.join(EN_CATALOGUE);
    let fr_path = root.join(FR_CATALOGUE);
    let en_exists = en_path.is_file();
    let fr_exists = fr_path.is_file();

    match (en_exists, fr_exists) {
        (false, false) => Ok(CatalogueState::NotBorn),
        (true, false) => Err(anyhow!(
            "{EN_CATALOGUE} exists but {FR_CATALOGUE} does not — a source catalogue without its FR pair is a half-born catalogue"
        )),
        (false, true) => Err(anyhow!(
            "{FR_CATALOGUE} exists but {EN_CATALOGUE} does not — EN is the source catalogue"
        )),
        (true, true) => {
            let en = parse_catalogue(&read(&en_path)?);
            let fr = parse_catalogue(&read(&fr_path)?);
            report_parse_problems(EN_CATALOGUE, &en)?;
            report_parse_problems(FR_CATALOGUE, &fr)?;

            let missing_fr = en
                .keys
                .difference(&fr.keys)
                .cloned()
                .collect::<Vec<String>>();
            let orphan_fr = fr
                .keys
                .difference(&en.keys)
                .cloned()
                .collect::<Vec<String>>();

            Ok(CatalogueState::Born(Coverage {
                en_total: en.keys.len(),
                fr_total: fr.keys.len(),
                missing_fr,
                orphan_fr,
                en_keys: en.keys,
            }))
        }
    }
}

fn read(path: &Path) -> Result<String> {
    std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))
}

fn report_parse_problems(name: &str, catalogue: &Catalogue) -> Result<()> {
    if !catalogue.malformed.is_empty() {
        let details = catalogue.malformed.join("; ");
        return Err(anyhow!("{name} is malformed: {details}"));
    }
    if !catalogue.duplicates.is_empty() {
        let details = catalogue.duplicates.join(", ");
        return Err(anyhow!("{name} has duplicate keys: {details}"));
    }
    Ok(())
}

fn parse_baseline(content: &str) -> Result<Baseline> {
    let mut state = None;
    let mut en_total = 0;
    let mut fr_missing = 0;

    for (index, raw) in content.lines().enumerate() {
        let line = raw.trim_end_matches('\r').trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((key, value)) = line.split_once(':') else {
            return Err(anyhow!(
                "{BASELINE} line {}: expected `key: value`",
                index.saturating_add(1)
            ));
        };
        let key = key.trim();
        let value = value.trim();
        match key {
            "state" => {
                state = Some(match value {
                    "no-catalogues" => BaselineState::NoCatalogues,
                    "catalogues" => BaselineState::Catalogues,
                    other => {
                        return Err(anyhow!(
                            "{BASELINE}: unknown state `{other}` (expected `no-catalogues` or `catalogues`)"
                        ))
                    }
                });
            }
            "en_total" => en_total = parse_count(value, "en_total")?,
            "fr_missing" => fr_missing = parse_count(value, "fr_missing")?,
            other => {
                return Err(anyhow!("{BASELINE}: unknown key `{other}`"));
            }
        }
    }

    let state = state.ok_or_else(|| anyhow!("{BASELINE}: missing `state`"))?;
    Ok(Baseline {
        state,
        en_total,
        fr_missing,
    })
}

fn parse_count(value: &str, name: &str) -> Result<usize> {
    value
        .parse::<usize>()
        .with_context(|| format!("{BASELINE}: `{name}` is not a number"))
}

fn read_baseline(root: &Path) -> Result<Baseline> {
    let path = root.join(BASELINE);
    if !path.is_file() {
        return Err(anyhow!(
            "missing {BASELINE} — commit the generated baseline so the tracked state is explicit"
        ));
    }
    parse_baseline(&read(&path)?)
}

pub fn check(root: &Path) -> Result<()> {
    let baseline = read_baseline(root)?;
    let state = measure(root)?;
    let used = match &state {
        CatalogueState::NotBorn => BTreeSet::new(),
        CatalogueState::Born(coverage) => gate::scan_usage(root, &coverage.en_keys)?,
    };

    let verdict = gate::evaluate(&baseline, &state, &used);
    print!("{}", verdict.report);

    if verdict.is_ok() {
        return Ok(());
    }
    eprintln!(
        "i18n-coverage: {} rule violation(s):",
        verdict.problems.len()
    );
    for problem in &verdict.problems {
        eprintln!("  - {problem}");
    }
    bail!("i18n coverage gate failed")
}

pub fn write_baseline(root: &Path) -> Result<()> {
    let content = match measure(root)? {
        CatalogueState::NotBorn => {
            format!("{BASELINE_HEADER}state: no-catalogues\nen_total: 0\nfr_missing: 0\n")
        }
        CatalogueState::Born(coverage) => format!(
            "{BASELINE_HEADER}state: catalogues\nen_total: {}\nfr_missing: {}\n",
            coverage.en_total,
            coverage.missing_fr.len()
        ),
    };

    let path = root.join(BASELINE);
    std::fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
    println!("i18n-coverage: wrote {BASELINE}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parser_reads_tab_separated_keys() {
        let catalogue = parse_catalogue("screen.a\tA\ncmd.b.title\tB\n");
        assert_eq!(catalogue.keys.len(), 2);
        assert!(catalogue.duplicates.is_empty());
        assert!(catalogue.malformed.is_empty());
    }

    #[test]
    fn parser_reports_duplicates() {
        let catalogue = parse_catalogue("screen.a\tA\nscreen.a\tAgain\n");
        assert_eq!(catalogue.duplicates, vec!["screen.a".to_string()]);
    }

    #[test]
    fn parser_reports_malformed_rows_instead_of_passing() {
        let catalogue = parse_catalogue("screen.a\tA\nno-tab-here\n\tempty-key\n");
        assert_eq!(catalogue.malformed.len(), 2);
    }

    #[test]
    fn baseline_parser_reads_the_not_born_state() {
        let baseline =
            parse_baseline("# header\nstate: no-catalogues\nen_total: 0\nfr_missing: 0\n")
                .expect("valid baseline");
        assert_eq!(baseline.state, BaselineState::NoCatalogues);
    }

    #[test]
    fn baseline_parser_reads_a_real_measurement() {
        let baseline =
            parse_baseline("state: catalogues\nen_total: 19\nfr_missing: 0\n").expect("valid");
        assert_eq!(baseline.state, BaselineState::Catalogues);
        assert_eq!(baseline.en_total, 19);
        assert_eq!(baseline.fr_missing, 0);
    }

    #[test]
    fn baseline_parser_rejects_unknown_state() {
        assert!(parse_baseline("state: maybe\n").is_err());
        assert!(parse_baseline("en_total: 1\n").is_err());
        assert!(parse_baseline("state: catalogues\nen_total: many\n").is_err());
    }
}
