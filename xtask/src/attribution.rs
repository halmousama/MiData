//! D30 attribution gate: the second term list (`terms.rs`) over the tree, plus the commit-message
//! check that `tools/hooks/commit-msg` invokes.
//!
//! **The rule (P0-14 (d)).** The term list targets *attribution* — trailers and claims of
//! authorship/provenance — not *reference*. A vendor name naming an integration target is a
//! reference: `docs/architecture.md` names an LLM vendor only to define the API dialect the app
//! speaks, and that must not fail the gate. In-tree hits are therefore triaged into
//! `docs/banned-names.baseline` with a recorded reason:
//!
//! - `reference` — the hit names an integration/compatibility target, or documents the ban itself
//!   (the devlog and the contributor docs necessarily discuss the trailer). Allowed.
//! - `attribution` — a claim of authorship/provenance. **Never allowlisted**: an allowlist entry
//!   with that reason is a gate error, and a commit message carrying one is rejected outright.
//!
//! **The ratchet.** The allowlist is a list of pre-existing violations that may only shrink: a new
//! hit fails, and an entry with no matching hit is stale and fails until the baseline is regenerated
//! with `cargo xtask banned-names --write-baseline`. This mirrors `docs/file-budget.baseline` and
//! `docs/i18n-coverage.baseline`.

use crate::{gates, source, terms};
use anyhow::{anyhow, bail, Context, Result};
use std::collections::BTreeSet;
use std::path::Path;

pub const BASELINE: &str = "docs/banned-names.baseline";

const BASELINE_HEADER: &str = "\
# GENERATED by `cargo xtask banned-names --write-baseline` — do not hand-edit without review.\n\
# Pre-existing D30 hits, triaged: path<TAB>term<TAB>reason.\n\
# reason `reference`: the term names an integration/compatibility target or documents the ban itself.\n\
# reason `attribution` is never allowed — an attribution claim is fixed, not allowlisted.\n\
# The list is a ratchet: it may only shrink. A new hit fails.\n\
# Note: this file is itself in `xtask/src/gates.rs::ALLOWED_PATHS` (it must name the terms it\n\
# allows), so it is exempt from the legacy product-name scan too — a shared-list side effect of\n\
# P0-14, recorded in the PR and harmless because the file only ever holds the allowlisted terms.\n";

/// One in-tree hit: a term on a line (1-based) of a scanned file.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Hit {
    pub path: String,
    pub term: String,
    /// What the term means — the baseline generator may not flatten every hit to `reference` (R2).
    pub kind: terms::TermKind,
    pub line: usize,
}

/// One allowlisted hit, keyed by (path, term) so the baseline is stable across line moves.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct AllowlistEntry {
    pub path: String,
    pub term: String,
}

/// Every term hit in a file's text. Pure, so tests can exercise the triage rules without a tree.
pub fn scan_text(relative: &str, content: &str) -> Vec<Hit> {
    terms::find(content)
        .into_iter()
        .map(|hit| Hit {
            path: relative.to_string(),
            term: hit.term_id.to_string(),
            kind: hit.kind,
            line: hit.line,
        })
        .collect()
}

/// Every hit in the repository, excluding the documented allowlist paths.
///
/// Two passes: the extension list (the legacy gate's, deliberately — the same files are the same
/// surfaces) and the bounded extensionless text files, so a hook script or a licence cannot escape
/// the gate (P0-14 review R3).
pub fn scan(root: &Path) -> Result<Vec<Hit>> {
    let mut hits = Vec::new();
    for extension in gates::TEXT_EXTENSIONS {
        for file in source::files_with_extension(root, extension)? {
            if gates::is_allowed_path(&file.relative) {
                continue;
            }
            let content = std::fs::read_to_string(&file.absolute)
                .with_context(|| format!("reading {}", file.relative))?;
            hits.extend(scan_text(&file.relative, &content));
        }
    }
    for file in source::extensionless_text_files(root)? {
        if gates::is_allowed_path(&file.relative) {
            continue;
        }
        let content = std::fs::read_to_string(&file.absolute)
            .with_context(|| format!("reading {}", file.relative))?;
        hits.extend(scan_text(&file.relative, &content));
    }
    hits.sort();
    hits.dedup();
    Ok(hits)
}

/// Pure ratchet evaluation: one message per problem, empty when the gate passes.
pub fn evaluate(current: &[Hit], allowlist: &[AllowlistEntry]) -> Vec<String> {
    let allowed: BTreeSet<(&str, &str)> = allowlist
        .iter()
        .map(|entry| (entry.path.as_str(), entry.term.as_str()))
        .collect();
    let measured: BTreeSet<(&str, &str)> = current
        .iter()
        .map(|hit| (hit.path.as_str(), hit.term.as_str()))
        .collect();

    let mut problems = Vec::new();

    for hit in current {
        if allowed.contains(&(hit.path.as_str(), hit.term.as_str())) {
            continue;
        }
        problems.push(format!(
            "{}:{}: `{}` is not in {BASELINE} — a new D30 hit fails; fix the surface, or triage a genuine reference into the allowlist with its reason",
            hit.path, hit.line, hit.term
        ));
    }

    for entry in allowlist {
        if measured.contains(&(entry.path.as_str(), entry.term.as_str())) {
            continue;
        }
        problems.push(format!(
            "{}: `{}`: stale allowlist entry (no matching hit) — the allowlist may only shrink; regenerate it with `cargo xtask banned-names --write-baseline`",
            entry.path, entry.term
        ));
    }

    problems
}

fn parse_baseline(content: &str) -> Result<Vec<AllowlistEntry>> {
    let mut entries = Vec::new();

    for (index, raw) in content.lines().enumerate() {
        let line = raw.trim_end_matches('\r');
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let mut fields = line.split('\t');
        let path = fields.next().unwrap_or_default().trim();
        let term = fields.next().unwrap_or_default().trim();
        let reason = fields.next().unwrap_or_default().trim();
        if path.is_empty() || term.is_empty() || reason.is_empty() || fields.next().is_some() {
            return Err(anyhow!(
                "{BASELINE} line {}: expected `path<TAB>term<TAB>reason`",
                index.saturating_add(1)
            ));
        }
        match reason {
            "reference" => {}
            "attribution" => {
                return Err(anyhow!(
                    "{BASELINE} line {}: an attribution claim is never allowlisted — remove the claim instead",
                    index.saturating_add(1)
                ))
            }
            other => {
                return Err(anyhow!(
                    "{BASELINE} line {}: unknown reason `{other}` (expected `reference`)",
                    index.saturating_add(1)
                ))
            }
        }
        entries.push(AllowlistEntry {
            path: path.to_string(),
            term: term.to_lowercase(),
        });
    }

    Ok(entries)
}

fn read_baseline(root: &Path) -> Result<Vec<AllowlistEntry>> {
    let path = root.join(BASELINE);
    if !path.is_file() {
        return Err(anyhow!(
            "missing {BASELINE} — commit the generated allowlist in the same change that adds the gate, so the gate is fatal from day one"
        ));
    }
    let content =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", BASELINE))?;
    parse_baseline(&content)
}

/// The `cargo xtask banned-names` tree gate.
pub fn check(root: &Path) -> Result<()> {
    let allowlist = read_baseline(root)?;
    let hits = scan(root)?;
    let problems = evaluate(&hits, &allowlist);
    let entries = allowlist.len();

    if problems.is_empty() {
        println!(
            "banned-names (attribution terms): OK — {} hit(s) in {} allowlisted entries, 0 new violation(s)",
            hits.len(),
            entries
        );
        return Ok(());
    }

    eprintln!(
        "banned-names (attribution terms): {} violation(s) against an allowlist of {entries}:",
        problems.len()
    );
    for problem in &problems {
        eprintln!("  - {problem}");
    }
    bail!("D30 attribution gate failed")
}

/// Render the allowlist from measured hits.
///
/// An attribution hit is a gate error, never a row: the generator used to flatten every hit to
/// `reference`, which let `--write-baseline` launder a real trailer into the allowlist (P0-14 review
/// R2). Nothing is written when this fails.
fn render_baseline(hits: &[Hit]) -> Result<String> {
    if let Some(claim) = hits
        .iter()
        .find(|hit| hit.kind == terms::TermKind::Attribution)
    {
        bail!(
            "{}:{}: `{}` is an attribution claim — never allowlisted; remove the claim instead of regenerating {BASELINE}",
            claim.path,
            claim.line,
            claim.term
        );
    }

    let unique: BTreeSet<(&str, &str)> = hits
        .iter()
        .map(|hit| (hit.path.as_str(), hit.term.as_str()))
        .collect();

    let mut content = String::from(BASELINE_HEADER);
    for (path, term) in &unique {
        content.push_str(path);
        content.push('\t');
        content.push_str(term);
        content.push_str("\treference\n");
    }
    Ok(content)
}

pub fn write_baseline(root: &Path) -> Result<()> {
    let hits = scan(root)?;
    let content = render_baseline(&hits)?;
    let entries = entries_in(&content);

    let path = root.join(BASELINE);
    std::fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
    println!(
        "banned-names (attribution terms): wrote {BASELINE} with {entries} allowlisted hit(s) across {} measured hit(s) — every row must be reviewed as a `reference`",
        hits.len()
    );
    Ok(())
}

/// Count the data rows in a rendered baseline (the header is `#`-prefixed).
fn entries_in(content: &str) -> usize {
    content
        .lines()
        .filter(|line| !line.trim().is_empty() && !line.starts_with('#'))
        .count()
}

/// Git's own comment lines are not part of the message the user wrote: `COMMIT_EDITMSG` carries the
/// template, including the `# >8` scissors line. Dropping them prevents a template from failing a
/// clean commit.
///
/// The scissors line is also a hard cut, because `git commit -v` (or `commit.verbose=true`) writes
/// the **diff** below it *uncommented*: scanning past it rejects a clean message whenever the diff
/// happens to mention a term — `log/devlog.md`, which records the D30 terms, did exactly that
/// (P0-14 review R1). Git itself discards everything from the scissors line on, so the hook does too.
fn strip_git_comments(message: &str) -> String {
    message
        .lines()
        .take_while(|line| !is_scissors(line))
        .filter(|line| !line.trim_start().starts_with('#'))
        .collect::<Vec<&str>>()
        .join("\n")
}

/// Git's scissors line: a comment line carrying the `>8` marker
/// (`# ------------------------ >8 ------------------------`).
fn is_scissors(line: &str) -> bool {
    let trimmed = line.trim();
    trimmed.starts_with('#') && trimmed.contains(">8")
}

/// The commit-message check (used by `xtask commit-msg` and therefore by the hook).
///
/// A commit message is an attribution surface by definition, so this check has no allowlist: any
/// trailer or vendor/model name is rejected. The term ids are printed, never the matched text.
pub fn check_message(message: &str) -> Result<()> {
    let hits = terms::find(&strip_git_comments(message));
    if hits.is_empty() {
        return Ok(());
    }

    eprintln!(
        "commit-msg: rejected — D30 bans attribution trailers and AI vendor/model names in commit messages:"
    );
    for hit in &hits {
        eprintln!("  line {}: `{}`", hit.line, hit.term_id);
    }
    eprintln!(
        "Remove the line and commit again; session notes belong in the gitignored plan/ kit."
    );
    bail!("commit message rejected by the D30 attribution gate")
}

pub fn check_message_file(path: &Path) -> Result<()> {
    let message = std::fs::read_to_string(path)
        .with_context(|| format!("reading the commit message {}", path.display()))?;
    check_message(&message)
}

