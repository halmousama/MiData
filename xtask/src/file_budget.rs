//! File-budget gate: 500-line soft cap per Rust file, 800-line alarm.
//!
//! The violation list is a **ratchet**: `docs/file-budget.baseline` records today's offenders (now
//! zero) and the list may only shrink. A new file over the cap fails; an existing offender that
//! grows fails; a baseline entry that is no longer an offender is stale and must be regenerated.
//! This is how "the list may only shrink" is a fact instead of a review habit (AGENTS.md rule 13).

use crate::source;
use anyhow::{anyhow, bail, Context, Result};
use std::collections::BTreeMap;
use std::path::Path;

pub const SOFT_LIMIT: usize = 500;
pub const ALARM_LIMIT: usize = 800;
pub const BASELINE: &str = "docs/file-budget.baseline";

const BASELINE_HEADER: &str =
    "# GENERATED by `cargo xtask file-budget --write-baseline` — do not hand-edit.\n\
# A violation is a Rust file over the 500-line soft cap (alarm at 800).\n\
# The list is a ratchet: it may only shrink. path<TAB>lines\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileLines {
    pub path: String,
    pub lines: usize,
}

/// Measure every Rust source file in the repository.
pub fn measure(root: &Path) -> Result<Vec<FileLines>> {
    let files = source::rust_files(root)?;
    let mut measured = Vec::with_capacity(files.len());
    for file in files {
        let content = std::fs::read_to_string(&file.absolute)
            .with_context(|| format!("reading {}", file.relative))?;
        measured.push(FileLines {
            path: file.relative,
            lines: content.lines().count(),
        });
    }
    Ok(measured)
}

fn offenders(files: &[FileLines]) -> Vec<FileLines> {
    files
        .iter()
        .filter(|file| file.lines > SOFT_LIMIT)
        .cloned()
        .collect()
}

/// Pure ratchet evaluation: returns one message per violation, empty when the gate passes.
pub fn evaluate(current: &[FileLines], baseline: &[FileLines]) -> Vec<String> {
    let baseline_map: BTreeMap<&str, usize> = baseline
        .iter()
        .map(|file| (file.path.as_str(), file.lines))
        .collect();
    let current_offenders = offenders(current);
    let current_paths: BTreeMap<&str, usize> = current_offenders
        .iter()
        .map(|file| (file.path.as_str(), file.lines))
        .collect();

    let mut problems = Vec::new();

    for file in &current_offenders {
        let alarm = if file.lines > ALARM_LIMIT {
            format!(" (ALARM: over {ALARM_LIMIT})")
        } else {
            String::new()
        };
        match baseline_map.get(file.path.as_str()) {
            Some(previous) if file.lines > *previous => problems.push(format!(
                "{}: grew from {previous} to {} lines{}{}",
                file.path,
                file.lines,
                alarm,
                ratchet_hint()
            )),
            Some(_) => {}
            None => problems.push(format!(
                "{}: new violation at {} lines (soft cap {SOFT_LIMIT}){}",
                file.path, file.lines, alarm
            )),
        }
    }

    for file in baseline {
        if !current_paths.contains_key(file.path.as_str()) {
            problems.push(format!(
                "{}: stale baseline entry (now under the cap) — the list may only shrink, regenerate with `cargo xtask file-budget --write-baseline`",
                file.path
            ));
        }
    }

    problems
}

fn ratchet_hint() -> &'static str {
    " — split the file or record a gaps entry, then regenerate the baseline"
}

fn read_baseline(path: &Path) -> Result<Vec<FileLines>> {
    if !path.is_file() {
        return Err(anyhow!(
            "missing {} — commit the generated baseline in the same change that adds the gate",
            BASELINE
        ));
    }
    let content =
        std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    parse_baseline(&content)
}

fn parse_baseline(content: &str) -> Result<Vec<FileLines>> {
    let mut entries = Vec::new();
    for (index, raw) in content.lines().enumerate() {
        let line = raw.trim_end_matches('\r');
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((path, lines)) = line.split_once('\t') else {
            return Err(anyhow!(
                "{} line {}: expected `path<TAB>lines`",
                BASELINE,
                index.saturating_add(1)
            ));
        };
        let lines: usize = lines.trim().parse().with_context(|| {
            format!(
                "{BASELINE} line {}: invalid line count",
                index.saturating_add(1)
            )
        })?;
        entries.push(FileLines {
            path: path.trim().to_string(),
            lines,
        });
    }
    Ok(entries)
}

pub fn check(root: &Path) -> Result<()> {
    let current = measure(root)?;
    let baseline = read_baseline(&root.join(BASELINE))?;
    let problems = evaluate(&current, &baseline);

    if problems.is_empty() {
        let alarm = current
            .iter()
            .filter(|file| file.lines > ALARM_LIMIT)
            .count();
        println!(
            "file-budget: OK — {} Rust file(s) scanned, 0 over the {SOFT_LIMIT}-line soft cap (alarm {ALARM_LIMIT}: {alarm})",
            current.len()
        );
        return Ok(());
    }

    eprintln!("file-budget: {} violation(s):", problems.len());
    for problem in &problems {
        eprintln!("  - {problem}");
    }
    bail!("file budget failed")
}

pub fn write_baseline(root: &Path) -> Result<()> {
    let current = measure(root)?;
    let mut content = String::from(BASELINE_HEADER);
    for file in offenders(&current) {
        content.push_str(&file.path);
        content.push('\t');
        content.push_str(&file.lines.to_string());
        content.push('\n');
    }
    let path = root.join(BASELINE);
    std::fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
    println!(
        "file-budget: wrote {BASELINE} with {} violation(s) across {} scanned file(s)",
        offenders(&current).len(),
        current.len()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(path: &str, lines: usize) -> FileLines {
        FileLines {
            path: path.to_string(),
            lines,
        }
    }

    #[test]
    fn file_over_soft_cap_is_a_violation() {
        let problems = evaluate(&[file("xtask/src/big.rs", 501)], &[]);
        assert_eq!(problems.len(), 1);
        assert!(problems[0].contains("new violation"));
    }

    #[test]
    fn file_at_soft_cap_is_accepted() {
        assert!(evaluate(&[file("xtask/src/ok.rs", 500)], &[]).is_empty());
    }

    #[test]
    fn recorded_offender_may_shrink_but_not_grow() {
        let baseline = vec![file("xtask/src/big.rs", 600)];
        assert!(evaluate(&[file("xtask/src/big.rs", 550)], &baseline).is_empty());
        let problems = evaluate(&[file("xtask/src/big.rs", 650)], &baseline);
        assert_eq!(problems.len(), 1);
        assert!(problems[0].contains("grew from 600 to 650"));
    }

    #[test]
    fn alarm_is_reported_for_files_over_800_lines() {
        let problems = evaluate(&[file("xtask/src/huge.rs", 900)], &[]);
        assert_eq!(problems.len(), 1);
        assert!(problems[0].contains("ALARM"));
    }

    #[test]
    fn stale_baseline_entry_fails_so_the_list_can_only_shrink() {
        let baseline = vec![file("xtask/src/big.rs", 600)];
        let problems = evaluate(&[file("xtask/src/big.rs", 400)], &baseline);
        assert_eq!(problems.len(), 1);
        assert!(problems[0].contains("stale baseline entry"));
    }

    #[test]
    fn baseline_parser_reads_tab_separated_entries() {
        let parsed = parse_baseline("# header\nxtask/src/a.rs\t600\n\n").expect("valid baseline");
        assert_eq!(parsed, vec![file("xtask/src/a.rs", 600)]);
    }

    #[test]
    fn baseline_parser_rejects_malformed_rows() {
        assert!(parse_baseline("not-a-row").is_err());
        assert!(parse_baseline("xtask/src/a.rs\tmany").is_err());
    }
}
